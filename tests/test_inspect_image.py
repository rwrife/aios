def build_cpio_newc(entries):
    """Build a minimal "newc" cpio archive: entries is [(name, bytes), ...]."""
    out = bytearray()

    def write_entry(name, data):
        name_bytes = name.encode('utf-8') + b'\x00'
        fields = [0, 0o100644, 0, 0, 1, 0, len(data), 0, 0, 0, 0, len(name_bytes), 0]
        header = b'070701' + ''.join(f'{value:08X}' for value in fields).encode('ascii')
        assert len(header) == 110
        out.extend(header)
        out.extend(name_bytes)
        out.extend(b'\x00' * ((-len(out)) % 4))
        out.extend(data)
        out.extend(b'\x00' * ((-len(out)) % 4))

    for name, data in entries:
        write_entry(name, data)
    write_entry('TRAILER!!!', b'')
    return bytes(out)


def build_apkovl(path, world, repositories, services):
    """Build a minimal AIOS apkovl tarball (see apkovl/genapkovl-aios.sh)."""
    with tarfile.open(path, 'w:gz') as archive:
        def add_file(name, content: bytes, mode=0o644):
            info = tarfile.TarInfo(name)
            info.size = len(content)
            info.mode = mode
            archive.addfile(info, BytesIO(content))

        add_file('etc/apk/world', ('\n'.join(world) + '\n').encode())
        add_file('etc/apk/repositories', ('\n'.join(repositories) + '\n').encode())
        for level, service_names in services.items():
            for service in service_names:
                info = tarfile.TarInfo(f'etc/runlevels/{level}/{service}')
                info.type = tarfile.SYMTYPE
                info.linkname = f'/etc/init.d/{service}'
                archive.addfile(info)


