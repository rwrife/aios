class ModloopLayoutTests(unittest.TestCase):
    """Alpine's modloop keeps modules and firmware under modules/, not lib/."""

    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self.tmp.cleanup)
        self.base = Path(self.tmp.name)

    def test_alpine_modloop_layout_is_found(self):
        modloop = self.base / 'alpine'
        (modloop / 'modules' / KERNEL_VERSION).mkdir(parents=True)
        (modloop / 'modules' / 'firmware' / 'iwlwifi').mkdir(parents=True)
        self.assertEqual(inspect_image.find_modules_root(modloop), modloop / 'modules')
        self.assertEqual(
            inspect_image.find_firmware_root(modloop), modloop / 'modules' / 'firmware')

    def test_firmware_directory_is_not_mistaken_for_a_kernel_version(self):
        modloop = self.base / 'only-firmware'
        (modloop / 'modules' / 'firmware').mkdir(parents=True)
        self.assertIsNone(inspect_image.find_modules_root(modloop))
        self.assertEqual(inspect_image.section_modloop(modloop)['status'], 'unavailable')

    def test_rootfs_style_lib_layout_is_still_accepted(self):
        rootfs = self.base / 'rootfs'
        (rootfs / 'lib' / 'modules' / KERNEL_VERSION).mkdir(parents=True)
        (rootfs / 'lib' / 'firmware').mkdir(parents=True)
        self.assertEqual(inspect_image.find_modules_root(rootfs), rootfs / 'lib' / 'modules')
        self.assertEqual(inspect_image.find_firmware_root(rootfs), rootfs / 'lib' / 'firmware')


