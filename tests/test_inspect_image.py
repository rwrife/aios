class CpioParsingTests(unittest.TestCase):
    def test_round_trips_paths_and_sizes(self):
        archive = build_cpio_newc([
            ('init', b'#!/bin/sh\n'),
            ('etc/mdev.conf', b'.* root:root 660\n'),
        ])
        entries = inspect_image.parse_cpio_newc(archive)
        self.assertEqual(
            sorted((entry['path'], entry['size']) for entry in entries),
            sorted([('init', 10), ('etc/mdev.conf', 17)]),
        )

    def test_stops_at_trailer_and_ignores_nothing_after(self):
        archive = build_cpio_newc([('a', b'x')]) + b'garbage-that-must-be-ignored'
        entries = inspect_image.parse_cpio_newc(archive)
        self.assertEqual([entry['path'] for entry in entries], ['a'])

    def test_rejects_unknown_magic_instead_of_guessing(self):
        with self.assertRaises(ValueError):
            inspect_image.parse_cpio_newc(b'070707' + b'0' * 200)


