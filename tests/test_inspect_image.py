class ModaliasProbeTests(unittest.TestCase):
    def test_pci_probe_wildcards_subsystem_and_class(self):
        probe = inspect_image.pci_modalias_probe('8086:2725')
        self.assertEqual(probe, 'pci:v00008086d00002725sv*sd*bc*sc*i*')

    def test_usb_probe_wildcards_version_and_interface(self):
        probe = inspect_image.usb_modalias_probe('0e8d:7961')
        self.assertEqual(probe, 'usb:v0E8Dp7961d*dc*dsc*dp*ic*isc*ip*in*')

    def test_matching_is_case_insensitive(self):
        probe = inspect_image.pci_modalias_probe('8086:2725')
        self.assertTrue(inspect_image.alias_matches_probe(
            'pci:v00008086d00002725sv*sd*bc*sc*i*', probe))
        self.assertTrue(inspect_image.alias_matches_probe(
            'PCI:V00008086D00002725SV*SD*BC*SC*I*', probe))

    def test_vendor_wildcard_alias_matches_concrete_device(self):
        probe = inspect_image.pci_modalias_probe('8086:2725')
        self.assertTrue(inspect_image.alias_matches_probe(
            'pci:v00008086d*sv*sd*bc*sc*i*', probe))

    def test_subsystem_specific_alias_still_matches_a_vendor_device_probe(self):
        probe = inspect_image.pci_modalias_probe('8086:2725')
        self.assertTrue(inspect_image.alias_matches_probe(
            'pci:v00008086d00002725sv00008086sd00000024bc*sc*i*', probe))

    def test_unrelated_device_does_not_match(self):
        probe = inspect_image.pci_modalias_probe('dead:beef')
        self.assertFalse(inspect_image.alias_matches_probe(
            'pci:v00008086d00002725sv*sd*bc*sc*i*', probe))

    def test_usb_alias_matching(self):
        probe = inspect_image.usb_modalias_probe('0e8d:7961')
        self.assertTrue(inspect_image.alias_matches_probe(
            'usb:v0E8Dp7961d*dc*dsc*dp*icFFisc*ip*in*', probe))
        self.assertFalse(inspect_image.alias_matches_probe(
            'usb:v0E8Dp7662d*dc*dsc*dp*ic*isc*ip*in*', probe))


